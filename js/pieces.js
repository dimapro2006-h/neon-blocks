// Неонові кольори блоків
const COLORS = ['#ff4d6d', '#ffb703', '#06d6a0', '#4cc9f0', '#7c5cff', '#f72585', '#3a86ff', '#fb5607'];

function randomItem(list) {
  return list[Math.floor(Math.random() * list.length)];
}

// Створює фігуру: клітинки, розмір (рядки × стовпці) і колір
function makePiece(cells) {
  return {
    cells,
    rows: Math.max(...cells.map(c => c[0])) + 1,
    cols: Math.max(...cells.map(c => c[1])) + 1,
    color: randomItem(COLORS),
  };
}

function randomPiece() {
  return makePiece(randomItem(SHAPES));
}
